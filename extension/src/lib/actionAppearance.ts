/**
 * Toolbar (action) icon for a session status.
 *
 * - Not listening: muted grey icon, no badge.
 * - Listening (live or simulation, including starting/reconnecting): soft blue icon, no badge.
 *   Chrome's own tab-capture indicator also shows on the captured tab.
 * - Error: grey icon with a small "ERR" badge, so a failure is noticed during a meeting.
 * The tooltip (title) still says what is happening.
 */
import type { SessionStatus } from './settings.js';

export type ActionIconSet = 'idle' | 'active';

export const ACTION_ICON_SIZES = [16, 32, 48, 128] as const;

/** Files generated by scripts/generate-icons.mjs into public/icons (copied to dist/icons). */
export const actionIconPaths = (set: ActionIconSet): Record<string, string> =>
  Object.fromEntries(ACTION_ICON_SIZES.map((size) => [String(size), `icons/${set}${size}.png`]));

export interface ActionAppearance {
  icon: ActionIconSet;
  badgeText: string;
  badgeColor: string;
  title: string;
}

const ERROR_BADGE_COLOR = '#b45309';

export function actionAppearance(status: SessionStatus): ActionAppearance {
  const active = status.phase === 'live' || status.phase === 'starting' || status.phase === 'reconnecting';
  const isError = status.phase === 'error';
  return {
    icon: active ? 'active' : 'idle',
    badgeText: isError ? 'ERR' : '',
    badgeColor: ERROR_BADGE_COLOR,
    title: active
      ? `Meeting Copilot: ${status.mode === 'simulation' ? 'simulation (test mode)' : `listening to "${status.tabTitle ?? 'tab'}"`}`
      : isError
        ? `Meeting Copilot: ${status.message ?? 'error'}`
        : 'Meeting Copilot',
  };
}
